-- ==================================================
-- Part 2: Insert With an Autogenerated Key
-- ==================================================

-- 3. Insert a payment of $49.99 for Emma's order
-- using PaymentMethodId 1.
-- PaymentId is omitted so PostgreSQL generates it.

INSERT INTO Payment (
    OrderId,
    PaymentMethodId,
    Amount
)
VALUES (
    (
        SELECT co.OrderId
        FROM CustomerOrder AS co
        INNER JOIN Customer AS c
            ON co.CustomerId = c.CustomerId
        WHERE c.CustomerName = 'Emma Rivera'
        ORDER BY co.OrderId
        LIMIT 1
    ),
    1,
    49.99
);

-- Answer:
-- INSERT 0 1
-- One payment was inserted.
-- PostgreSQL automatically generated the PaymentId.


-- Verify Emma's payment.

SELECT
    p.PaymentId,
    c.CustomerName,
    co.OrderId,
    pm.MethodName,
    p.Amount
FROM Payment AS p
INNER JOIN CustomerOrder AS co
    ON p.OrderId = co.OrderId
INNER JOIN Customer AS c
    ON co.CustomerId = c.CustomerId
INNER JOIN PaymentMethod AS pm
    ON p.PaymentMethodId = pm.PaymentMethodId
WHERE c.CustomerName = 'Emma Rivera';

-- Answer:
-- 1 row returned.
-- PaymentId 1 was automatically generated by PostgreSQL.
-- Emma Rivera's OrderId 1 has a $49.99 payment
-- using the Credit Card payment method.


