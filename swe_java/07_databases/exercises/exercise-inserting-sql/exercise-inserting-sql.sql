-- Display all customers and their orders.

SELECT
    c.CustomerId,
    c.CustomerName,
    co.OrderId,
    co.OrderDate
FROM Customer AS c
LEFT JOIN CustomerOrder AS co
    ON c.CustomerId = co.CustomerId
ORDER BY c.CustomerId, co.OrderId;

-- Answer:
-- 5 rows returned.
-- Emma Rivera, Noah Gray, Liam Davis, and Olivia Brooks
-- each have an order dated 2026-08-06.
-- Sophia Martinez was inserted as a customer but does not
-- have an order, so her OrderId and OrderDate are NULL.


