-- 4. Try inserting a payment using
-- PaymentMethodId 999.
--


INSERT INTO Payment (
    OrderId,
    PaymentMethodId,
    Amount
)
VALUES (
    (
        SELECT co.OrderId
        FROM CustomerOrder AS co
        INNER JOIN Customer AS c
            ON co.CustomerId = c.CustomerId
        WHERE c.CustomerName = 'Noah Gray'
        ORDER BY co.OrderId
        LIMIT 1
    ),
    999,
    20.00
);

-- Answer:
-- The INSERT failed because PaymentMethodId 999
-- does not exist in the PaymentMethod table.

-- PostgreSQL error message:
-- ERROR: insert or update on table "payment" violates foreign key
-- constraint "payment_paymentmethodid_fkey"
-- SQL state: 23503
-- Detail: Key (paymentmethodid)=(999) is not present in table
-- "paymentmethod".

SELECT *
FROM Payment
WHERE PaymentMethodId = 999;

-- Answer:
-- 0 rows returned.
-- PostgreSQL rejected the invalid payment because
-- PaymentMethodId 999 does not exist.


